import os
import glob
import re

ROOT_DIR = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))

COURSES = {
    "CSS": { "title": "CSS3 Curriculum", "badge": "32 Modules" },
    "C": { "title": "C Language", "badge": "24 Modules" },
    "CPP": { "title": "C++ Standard Curriculum", "badge": "23 Modules" },
    "HTML": "HTML5 Curriculum", # string or dict format
    "HTML": { "title": "HTML5 Curriculum", "badge": "32 Modules" },
    "JS": { "title": "JavaScript Curriculum", "badge": "25 Modules" },
    "Python": { "title": "Python 3 Curriculum", "badge": "32 Modules" },
    "Java": { "title": "Java SE Curriculum", "badge": "24 Modules" },
    "SQL": { "title": "SQL Database Curriculum", "badge": "30 Modules" },
    "Git-and-GitHub": { "title": "Git & GitHub Curriculum", "badge": "30 Modules" }
}

def natural_sort_key(s):
    return [int(text) if text.isdigit() else text.lower() for text in re.split(r'(\d+)', s)]

def format_title(filename):
    name = filename.replace('.html', '')
    name = name.replace('-', ' ')
    match = re.match(r'^(\d+)\s+(.*)$', name)
    if match:
        num = match.group(1)
        rest = match.group(2)
        words = [w.capitalize() for w in rest.split(' ')]
        return f"{num}. {' '.join(words)}"
    words = [w.capitalize() for w in name.split(' ')]
    return ' '.join(words)

def scan_course_directory(course_dir):
    course_path = os.path.join(ROOT_DIR, course_dir)
    if not os.path.exists(course_path):
        return []

    lessons = []

    # 1. Check overview page
    if os.path.exists(os.path.join(course_path, "index.html")):
        lessons.append({ "title": "Curriculum Overview", "href": "index.html" })

    # List all items in course_path
    items = os.listdir(course_path)
    sorted_items = sorted(items, key=natural_sort_key)

    for item in sorted_items:
        item_path = os.path.join(course_path, item)

        # Ignore hidden files, assets, special files
        if item.startswith('.') or item in ['index.html', '00-README.html', 'assets', 'node_modules']:
            continue

        if os.path.isfile(item_path) and item.endswith('.html'):
            # Standalone lesson file
            lessons.append({
                "title": format_title(item),
                "href": item
            })
        elif os.path.isdir(item_path):
            # Module folder
            sub_files = os.listdir(item_path)
            sorted_sub = sorted(sub_files, key=natural_sort_key)
            sub_items = []

            for sub in sorted_sub:
                if sub.startswith('.') or sub == 'index.html' or not sub.endswith('.html'):
                    continue
                sub_items.append({
                    "title": format_title(sub),
                    "href": f"{item}/{sub}"
                })

            module_node = {
                "title": format_title(item),
                "href": f"{item}/index.html" if os.path.exists(os.path.join(item_path, "index.html")) else (sub_items[0]["href"] if sub_items else "#")
            }
            if sub_items:
                module_node["subItems"] = sub_items

            lessons.append(module_node)

    return lessons

def generate_sidebar_data_js():
    data_out = {}
    for course_dir, meta in COURSES.items():
        lessons = scan_course_directory(course_dir)
        data_out[course_dir] = {
            "title": meta["title"],
            "badge": meta["badge"],
            "lessons": lessons
        }

    # Format JS file content
    import json
    js_json = json.dumps(data_out, indent=2)

    js_content = f"""/**
 * Centralized Sidebar Data Repository - Learn Coding Developer Hub
 * Auto-generated by scripts/generate_sidebar_data.py via GitHub Actions
 * Single Source of Truth for Navigation Metadata Across All 9 Course Tracks
 */
window.SIDEBAR_DATA = {js_json};
"""

    out_file = os.path.join(ROOT_DIR, "assets", "js", "sidebar-data.js")
    with open(out_file, "w", encoding="utf-8") as f:
        f.write(js_content)

    print(f"Successfully generated sidebar-data.js for {len(data_out)} course tracks.")

if __name__ == "__main__":
    generate_sidebar_data_js()
